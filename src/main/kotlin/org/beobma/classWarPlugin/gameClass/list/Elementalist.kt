    private inner class OrangeSkill : Skill() {
        override val name = "<bold>방출"

        override val description = listOf(
            "<gray>저장된 원소가 있을 때에만 사용할 수 있다.",
            "<gray>사용 후 원소는 소모된다.",
            "",
            "<gray>저장된 원소를 방출시킨다.",
            "<gray> - 방출:",
            "<gray>  - 흙: 바라보는 방향으로 4초간 돌벽을 설치한다.",
            "<gray>  - 불: 자신의 위치에 4초간 불타는 지대를 만들어 적이 {keyword:Burn} 상태라면 {keyword:Burn} 지속시간은 줄어들지 않는다.",
            "<gray>  - 물: 자신의 위치에 5초간 물의 영역을 만들어 적의 이동 속도를 20% 감소시키고 1초마다 자신의 체력을 1 회복한다.",
            "<gray>  - 공기: 바라보는 방향으로 3초간 유지되는 소용돌이를 만들어 날린다. 주변 적은 중앙으로 끌어당겨진다.",
        )

        override val cooldown = ELEMENTALIST_RELEASE_COOLDOWN_SECONDS

        override fun isUseSuccess(): Boolean = runtime?.canCast(ElementCastMode.RELEASE) == true

        override fun use() {
            runtime?.cast(ElementCastMode.RELEASE)
            /*
             * ====================================================
             * 방출 구현 의도
             * ====================================================
             *
             * "발현"이 직접적인 공격이라면,
             * "방출"은 원소를 공간에 남기는 영역형 기술이다.
             *
             * 영역 효과는 Bukkit 블록을 실제로 영구 변경하기보다는
             * Display Entity / Particle / 충돌 판정 등을 이용하는 것을 권장한다.
             *
             * 임시 블록을 실제 설치한다면 반드시 종료 시 원상복구하며,
             * 기존 맵 블록을 파괴하거나 덮어써서는 안 된다.
             *
             *
             * ----------------------------------------------------
             * EARTH / 흙 - 돌벽
             * ----------------------------------------------------
             *
             * 플레이어가 바라보는 방향의 앞쪽에
             * 4초간 유지되는 임시 돌벽을 생성한다.
             *
             * 의도:
             * - 플레이어 이동 차단
             * - 원거리 투사체 차단
             * - 시야 차단
             *
             * 벽의 정확한 가로/세로 크기는 기존 프로젝트의
             * 스킬 범위 표준에 맞춰 결정한다.
             *
             * 4초가 지나면 완전히 제거.
             *
             * FIRE → EARTH 융합이면
             * 벽에 화염 속성을 추가한다.
             *
             * 예:
             * - 벽에 접촉한 적 Burn
             * - 혹은 벽 주변 화염 효과
             *
             * 핵심은 "흙 스킬의 기존 기능 + 불의 특성"을 유지하는 것이다.
             *
             *
             * ----------------------------------------------------
             * FIRE / 불 - 불타는 지대
             * ----------------------------------------------------
             *
             * 시전자 현재 위치를 중심으로 4초간 영역 생성.
             *
             * 이 스킬 자체는 설명상 별도의 직접 피해를 주지 않는다.
             *
             * 대신 영역 안에 있는 적이 이미 Burn 상태라면
             * 그 적이 영역 안에 머무르는 동안 Burn 남은 시간이 감소하지 않는다.
             *
             * 예:
             *
             * Burn 2.4초 남음
             * -> 화염지대 진입
             * -> 3초 동안 머묾
             * -> 나왔을 때 여전히 약 2.4초
