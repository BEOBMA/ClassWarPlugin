    private inner class RedSkill : Skill() {
        override val name = "<bold>발현"

        override val description = listOf(
            "<gray>저장된 원소가 있을 때에만 사용할 수 있다.",
            "<gray>사용 후 원소는 소모된다.",
            "",
            "<gray>저장된 원소를 발현시킨다.",
            "<gray> - 발현:",
            "<gray>  - 흙: 암석을 발사하여 처음 적중한 적에게 4의 피해를 입히고 밀쳐낸다.",
            "<gray>  - 불: 화염구를 발사하여 처음 적중한 적에게 3의 피해를 입히고 3초간 {keyword:Burn} 상태로 만든다.",
            "<gray>  - 물: 물로 만들어진 창을 발사하여 적중한 최대 2명의 적에게 2.5의 피해를 입히고 이동 속도를 10% 감소시킨다.",
            "<gray>  - 공기: 압축된 공기를 발사하여 적중한 모든 적에게 2의 피해를 입힌다. 이 피해는 방어력을 20% 무시한다.",
        )

        override val cooldown = ELEMENTALIST_MANIFEST_COOLDOWN_SECONDS

        override fun isUseSuccess(): Boolean = runtime?.canCast(ElementCastMode.MANIFEST) == true

        override fun use() {
            runtime?.cast(ElementCastMode.MANIFEST)
            /*
             * ====================================================
             * 발현 구현 의도
             * ====================================================
             *
             * 현재 저장된 원소가 없다면 아무 효과도 발생시키지 않는다.
             *
             * 원소가 존재한다면:
             *
             * 1. 저장 원소를 확인한다.
             * 2. 해당 원소에 맞는 발현 공격을 준비한다.
             * 3. 공명 / 융합으로 인해 공격 속성이 변경되는지 계산한다.
             * 4. 공격을 생성한다.
             * 5. 원소를 소비한다.
             * 6. 최근 원소 소비 기록을 갱신한다.
             * 7. 해방 조건을 검사한다.
             * 8. 다음 원소 저장 처리를 한다.
             *
             *
             * ----------------------------------------------------
             * EARTH / 흙
             * ----------------------------------------------------
             *
             * 바라보는 방향으로 암석 투사체를 발사한다.
             *
             * - 첫 번째 적에게만 적중한다.
             * - 기본 피해 4.
             * - 적중한 적을 투사체 진행 방향으로 밀쳐낸다.
             * - 적에게 적중하면 투사체는 제거한다.
             *
             * AIR → EARTH 융합 상태라면
             * 일반적인 수평 넉백 대신 적을 지면 방향으로 떨어뜨리고
             * Fix를 적용해야 한다.
             *
             *
             * ----------------------------------------------------
             * FIRE / 불
             * ----------------------------------------------------
             *
             * 바라보는 방향으로 화염구를 발사한다.
             *
             * - 첫 번째 적에게 적중한다.
             * - 기본 피해 3.
             * - Burn 3초.
             *
             * AIR → FIRE라면 적중 지점에서 추가 폭발.
             * EARTH → FIRE라면 1초 뒤 지면에서 추가 폭발.
             * WATER → FIRE라면 대상의 둔화/Burn을 제거하고
             * TrueDamage 2를 추가 적용한다.
             *
             *
             * ----------------------------------------------------
             * WATER / 물
             * ----------------------------------------------------
             *
             * 직선으로 물의 창을 발사한다.
             *
             * - 플레이어를 관통한다.
             * - 최대 2명의 서로 다른 적까지만 피해.
             * - 같은 적에게 한 투사체가 여러 번 피해를 주지 않는다.
             * - 각 대상에게 피해 2.5.
             * - 이동속도 10% 감소.
             *
             * 둔화 지속시간은 프로젝트의 상태이상 시스템에 맞춰 설정하되,
             * 동일 효과가 중복되는 경우 무한 중첩되지 않도록 한다.
             *
             *
             * ----------------------------------------------------
             * AIR / 공기
             * ----------------------------------------------------
             *
             * 매우 빠른 직선형 압축 공기 공격.
             *
             * - 적을 관통한다.
             * - 경로에 있는 모든 서로 다른 적에게 2 피해.
             * - 방어력 20% 무시.
             *
             * "20% 무시"는 최종 피해 20% 증가가 아니라,
             * 기존 프로젝트의 방어력 계산에서
             * 대상 방어력의 20%를 무시하는 효과로 구현한다.
             *
             * WATER → AIR라면 적중한 적에게 Freezing 적용.
             * EARTH → AIR라면 공격 주변/적중 위치에 시야 감소 효과를 추가한다.
             */
        }
    }


