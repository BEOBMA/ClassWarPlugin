/*
 * ============================================================
 * 원소술사(Elementalist) 구현 개요
 * ============================================================
 *
 * [핵심 컨셉]
 *
 * 원소술사는 흙(Terra), 불(Ignis), 물(Aqua), 공기(Aer)의
 * 4원소를 순서대로 소비하면서 싸우는 L등급 고난도 클래스다.
 *
 * 단순히 "현재 원소에 따라 스킬 효과가 변한다"에서 끝나는 것이 아니라,
 * 최근에 어떤 원소를 어떤 순서로 소비했는지에 따라
 *
 * 1. 융합 - 서로 다른 원소 2개
 * 2. 공명 - 같은 원소 2개
 * 3. 해방 - 서로 다른 원소 3개
 *
 * 가 추가로 발생한다.
 *
 * 따라서 구현 시 "스킬 사용"과 "원소 소비"를 분리해서 관리하는 것을 권장한다.
 *
 *
 * ============================================================
 * 권장 상태 구조
 * ============================================================
 *
 * Element enum을 별도로 만드는 것을 권장한다.
 *
 * enum class Element {
 *     EARTH,  // 흙 / Terra
 *     FIRE,   // 불 / Ignis
 *     WATER,  // 물 / Aqua
 *     AIR     // 공기 / Aer
 * }
 *
 *
 * 플레이어별로 최소한 다음 상태가 필요하다.
 *
 * - 원소 배열
 *   앞으로 등장할 원소가 순서대로 저장된 큐.
 *
 * - 현재 저장된 원소
 *   스킬에서 실제로 소비할 수 있도록 "저장"된 배열 최전방 원소.
 *
 * - 최근 원소 소비 기록
 *   융합 / 공명 / 해방 판정을 위해
 *   Element + 소비 시각을 기록한다.
 *
 * - 공명으로 생성된 강화 대기 상태
 *   예:
 *      FIRE_RESONANCE_READY
 *      WATER_RESONANCE_READY
 *
 * - 직전에 사용한 원소 스킬의 정보
 *   특히 "불 → 공기", "불 → 흙"처럼
 *   앞 스킬의 효과를 뒤 스킬에 전달해야 하는 융합에 필요하다.
 *
 *
 * ============================================================
 * 원소 소비 처리 권장 순서
 * ============================================================
 *
 * 하나의 원소 스킬이 사용될 때 다음 순서를 권장한다.
 *
 * 1. 현재 저장된 원소 확인
 * 2. 사용할 Skill 종류 확인
 *      - Red = 발현
 *      - Orange = 방출
 *      - Yellow = 감응
 * 3. 해당 원소의 기본 효과 실행
 * 4. 현재 원소에 적용되어 있던 "공명 강화"가 있다면 적용
 * 5. 직전 원소와 현재 원소를 비교하여 융합 판정
 * 6. 최근 3개 원소를 확인하여 해방 판정
 * 7. 현재 원소 소비 기록 저장
 * 8. 원소 배열에서 해당 원소 제거
 * 9. Charge를 20 소모할 수 있다면 다음 원소 저장
 *
 * 단,
 * 융합 효과 중 "현재 스킬 자체를 변경해야 하는 효과"는
 * 실제 기본 효과를 실행하기 전에 계산해야 할 수도 있다.
 *
 * 따라서 실제 구현에서는
 *
 * prepareElementEffect()
 * -> applyFusionModifier()
 * -> applyResonanceModifier()
 * -> executeElementEffect()
 * -> checkLiberation()
 *
 * 같은 구조로 분리하는 것을 권장한다.
 *
 *
 * ============================================================
 * 3초 판정
 * ============================================================
 *
 * "3초 이내"는 두 원소의 소비 시각 차이를 의미한다.
 *
 * 예:
 *
 * 0.0초 FIRE
 * 2.0초 AIR
 *   -> FIRE → AIR 융합 발생
 *
 * 4.0초 WATER
 *   -> AIR → WATER는 2초 차이이므로 융합 발생
 *
 * 최근 3개의 원소가
 *
 * FIRE(0.0)
 * AIR(2.0)
 * WATER(4.0)
 *
 * 이라면 첫 번째 FIRE와 마지막 WATER의 차이가 4초이므로
 * 3원소 해방은 발생하지 않는 방식이 자연스럽다.
 *
 * 즉 해방은
 *
 * newest.time - oldest.time <= 3초
 *
 * 인 경우에만 발생시키는 것을 권장한다.
 *
 *
 * ============================================================
 * 중복 판정
 * ============================================================
 *
 * 융합과 해방은 동시에 발생할 수 있다.
 *
 * 예:
 *
 * FIRE → AIR → WATER
 *
 * AIR → WATER 융합이 발생하면서 동시에
 * FIRE/AIR/WATER 3원소 해방도 발생한다.
 *
 * 이것은 원소술사의 의도된 고점으로 취급한다.
 *
 * 반면 공명은 같은 원소 2개를 요구하기 때문에
 * "서로 다른 원소 3개"를 요구하는 해방과 동일한 원소열에서는
 * 동시에 발생하지 않는다.
 */


// ============================================================
// 밸런스 조정 상수
// ============================================================
//
// 현재 모두 0초로 설정되어 있다.
// 원소를 사용할 수 있는 빈도는 기본적으로
// "원소 저장에 필요한 Charge"에 의해 제한시키려는 의도.
//
// 추후 플레이 테스트 후 개별 스킬 자체에도 쿨타임이 필요하다면
// 이 값만 변경할 수 있도록 유지한다.
//
private const val ELEMENTALIST_MANIFEST_COOLDOWN_SECONDS = 5
private const val ELEMENTALIST_RELEASE_COOLDOWN_SECONDS = 5
private const val ELEMENTALIST_ATTUNE_COOLDOWN_SECONDS = 5
private const val ELEMENTALIST_TRANSPOSE_COOLDOWN_SECONDS = 0


class Elementalist : GameClass(), GameStatusHandler, GameEndHandler, PlayerDeathHandler,
    EnvironmentalDamageHandler {

    override val name = "<gray>원소술사"

    /*
     * L등급.
     *
     * 높은 기본 수치보다는
     *
     * - 앞으로 나올 원소 배열 계산
     * - 전위로 배열 조작
     * - 2원소 융합
     * - 동일 원소 공명
     * - 3원소 해방
     *
     * 을 동시에 계산해야 하는 높은 조작 난이도가 핵심이다.
     */
    override val rank = Rank.L

    override val classItemMaterial = Material.STICK

    /*
     * [주의]
     *
     * GreenSkill(전위)이 아래 skills 목록에는 현재 등록되어 있지 않다.
     *
     * 전위를 실제 사용 가능한 스킬로 만들 예정이라면:
     *
     *     GreenSkill()
     *
     * 을 이 목록에 추가해야 한다.
     *
     * 만약 별도의 조작키/특수 입력으로 전위를 구현할 예정이라면
     * 현재 구조 그대로 두어도 된다.
     */
    override var skills: List<Skill> = listOf(
        RedSkill(),
        OrangeSkill(),
        YellowSkill(),
        GreenSkill(),
    )

    /*
     * [주의]
     *
     * 현재 Passive()만 등록되어 있으므로
     * PassiveTwo / PassiveThree / PassiveFour는 실제 패시브 목록에 표시되지 않는다.
     *
     * 융합, 공명, 해방도 실제 패시브로 등록할 예정이라면:
     *
     * Passive(),
     * PassiveTwo(),
     * PassiveThree(),
     * PassiveFour()
     *
     * 로 변경해야 한다.
     *
     * 단순 설명 분리를 위해 클래스를 나눈 것이고
     * 실제 UI에는 4원소 하나만 표시하려는 의도라면 현 상태를 유지한다.
     */
    override var passives: List<BasePassive> = listOf(
        Passive(),
        PassiveTwo(),
        PassiveThree(),
        PassiveFour(),
    )

    private var runtime: ElementalistRuntime? = null

    override fun onBattleStart() {
        runtime?.cleanup()
        runtime = ElementalistRuntime(playerData).also(ElementalistRuntime::start)
    }

    override fun onGameTimePasses() = Unit

    override fun onGameEnd() {
        runtime?.cleanup()
        runtime = null
    }

    override fun onPlayerDeath() = onGameEnd()

    override fun onEnvironmentalDamage(event: EntityDamageEvent) {
        if (runtime?.consumeFallImmunity(event) == true) event.isCancelled = true
    }


